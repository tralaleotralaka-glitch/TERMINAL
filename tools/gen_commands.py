def main() -> None:
    seen = {}
    rows = []
    for cat, items in CATS.items():
        for name, desc in items:
            if name in seen:
                raise SystemExit(f"дубликат: {name} ({seen[name]} / {cat})")
            seen[name] = cat
            rows.append([name, desc, cat])
    print("команд:", len(rows), "| по категориям:", {c: len(v) for c, v in CATS.items()})
    if len(rows) != 500:
        raise SystemExit(f"нужно ровно 500, получилось {len(rows)}")

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "commands.js")
    body = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Каталог команд. Сгенерирован tools/gen_commands.py — не править вручную. */\n")
        f.write("globalThis.COMMANDS = ")
        f.write(body)
        f.write(";\n")
    print("записано:", out, os.path.getsize(out), "байт")


if __name__ == "__main__":
    main()
